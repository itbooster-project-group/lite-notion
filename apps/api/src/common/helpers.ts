/**
 * Email хранится уже нормализованным, поэтому уникальность обеспечивает обычный
 * `@unique`, а не функциональный индекс. Нормализация нужна и в DTO, и в сервисах,
 * чтобы значение оставалось каноническим независимо от того, прошёл ли вызов
 * через HTTP-слой.
 */
export function normalizeEmail(email: string): string {
  return email.trim().toLowerCase();
}
