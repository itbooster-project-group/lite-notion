/**
 * Окончательное удаление уничтожит записи, которые чтение корзины показывало не
 * внутри удаляемого: страницу, удалённую раньше и самостоятельно, но физически
 * лежащую в удаляемом поддереве или проекте. Вне своего родителя страница
 * существовать не может, поэтому сохранить её нельзя — остаётся сказать о ней до
 * того, как она погибнет.
 *
 * `409`, а не `400`: запрос корректен, он противоречит состоянию корзины. Повтор
 * с явным подтверждением выполняет удаление целиком.
 *
 * Живёт в общих ошибках, а не в модуле: одна и та же механика у страниц и у
 * проектов, и класть её в один из модулей значило бы сделать второй зависимым от
 * первого ради одного класса.
 */
export class PurgeConfirmationRequiredError extends Error {
  constructor(readonly titles: readonly string[]) {
    super('Confirm the deletion: these trash entries will be destroyed as well');
    this.name = 'PurgeConfirmationRequiredError';
  }

  /**
   * Тело ответа: причина первой строкой, дальше заголовки. `HttpExceptionFilter`
   * пропускает наружу только `error` и `message`, а `message` уже умеет быть
   * массивом строк — так отдаются validation messages. Поэтому перечень едет
   * туда, и единый формат ошибок остаётся нетронутым.
   *
   * Заголовки не подставляются и не обрезаются: страницу можно создать без
   * заголовка, и показывать «Без заголовка» за пользователя — дело интерфейса.
   */
  toMessage(): string[] {
    return [this.message, ...this.titles];
  }
}
